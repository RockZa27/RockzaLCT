/** Display name of a receiving-card model id, or "Unknown (0x....)" when the id is not in the list. */
export function receiverModelName(modelId: number): string {
  const id = modelId >>> 0;
  return RECEIVER_MODEL_NAMES.get(id) ?? `Unknown (0x${id.toString(16).toUpperCase().padStart(4, '0')})`;
}
